import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {startFixture} from './room-parity-fixture.mjs'
const require=createRequire(new URL('../../collector-worker/package.json',import.meta.url)),{chromium}=require('playwright-core')
const server=await startFixture(),browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true})
try {
  const page=await browser.newPage({viewport:{width:1680,height:1000}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:18601/__room-parity.html?role=customer&start_test=1&delay_unlock=1&pcm=1&caption=1')
  const start=page.getByRole('button',{name:'开始',exact:true})
  await start.waitFor();await start.click()
  await page.locator('.speech-runtime-initializing').waitFor()
  assert.equal(await page.evaluate(()=>window.fixture.calls.some(c=>c.path.endsWith('/runtime/start'))),false,'animation appears before any unlock/start response')
  assert.equal(await page.getByRole('button',{name:'开始中…',exact:true}).isDisabled(),true,'double start blocked during unlock')
  assert.equal(await page.locator('.startup-wave-completed').evaluate(e=>getComputedStyle(e).animationName),'none','white waveform must not oscillate')
  assert.equal(await page.locator('.startup-wave-flow').count(),3,'startup waiting needs three independent color passes')
  assert.match(await page.locator('.startup-wave-flow').first().evaluate(e=>getComputedStyle(e).animationName),/^startup-wave-layer-scan(?:-|$)/,'color waveform must keep moving while a real stage is waiting')
  assert.equal(await page.locator('.speech-runtime-initializing-progress').getAttribute('aria-valuenow'),'4')
  await page.evaluate(()=>{window.fixture.runtimePollLag=true;window.fixture.releaseUnlock()})
  await page.waitForFunction(()=>window.fixture.calls.some(c=>c.path.endsWith('/runtime/start')))
  await page.waitForTimeout(200)
  assert.equal(await page.locator('.speech-runtime-initializing').count(),1,'stale stopped snapshot must not hide accepted startup waiting')
  await page.evaluate(()=>window.fixture.runtimePollLag=false)
  await page.getByRole('button',{name:'暂停',exact:true}).waitFor()
  assert.equal(await page.locator('.speech-runtime-initializing').count(),1,'working flag and captions cannot end first sound waiting')
  await page.evaluate(()=>window.fixture.startup={session_id:window.fixture.session,stage:'generating_voice',percent:65})
  await page.waitForFunction(()=>document.querySelector('.speech-runtime-initializing-progress')?.getAttribute('aria-valuenow')==='65')
  assert.match(await page.locator('.speech-runtime-initializing-copy strong').innerText(),/正在生成主播声音/)
  await page.evaluate(()=>window.fixture.startup={session_id:window.fixture.session,stage:'reading_plan',percent:12})
  await page.waitForTimeout(5500)
  assert.equal(await page.locator('.speech-runtime-initializing-progress').getAttribute('aria-valuenow'),'65','late status cannot move waveform backwards')
  await page.evaluate(()=>window.fixture.startup={session_id:window.fixture.session,stage:'waiting_playback',percent:96})
  await page.waitForFunction(()=>document.querySelector('.speech-runtime-initializing-progress')?.getAttribute('aria-valuenow')==='96')
  await page.screenshot({path:'../deploy/validation/white-wave-startup.png',fullPage:true})
  await page.evaluate(()=>window.fixture.pcmController.enqueue(new Uint8Array(960)))
  await page.waitForFunction(()=>window.fixture.sources.length>0)
  assert.equal(await page.locator('.speech-runtime-initializing').count(),1,'silent PCM cannot hide waiting')
  await page.evaluate(()=>{const pcm=new Uint8Array(960);new DataView(pcm.buffer).setInt16(0,1500,true);window.fixture.pcmController.enqueue(pcm)})
  await page.locator('.speech-runtime-initializing').waitFor({state:'hidden'})
  await page.getByText('正在回答保存问题哟',{exact:true}).waitFor()
  await page.getByRole('button',{name:'停止',exact:true}).click()
  await start.waitFor()
  await page.evaluate(()=>window.fixture.startFailed=true)
  await start.click()
  await page.getByText('模拟启动失败',{exact:false}).first().waitFor()
  assert.equal(await page.locator('.speech-runtime-initializing').count(),0,'failed startup must not spin forever')
  assert.deepEqual(errors,[])
  assert.ok((await page.evaluate(()=>window.fixture.calls.filter(c=>c.method!=='GET'))).every(c=>c.path.includes('/receivers/')||c.path.endsWith('/runtime/start')||c.path.endsWith('/runtime/stop')),'all mutations stay in mocked fixture')
  console.log('PASS: actual click shows animation before unlock; double start guard; stale snapshot/captions/silent PCM keep waiting; first played sound ends waiting; failure exits')
}finally{await browser.close();await server.close()}
