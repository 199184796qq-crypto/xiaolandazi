import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const require = createRequire(new URL('../../collector-worker/package.json', import.meta.url))
const { chromium } = require('playwright-core')
const output = resolve(process.env.MODEL_TEST_CONTROLS_OUTPUT || '../work/model-test-controls')
await mkdir(output, { recursive: true })
const profile = { id: 'qwen', name: 'Qwen测试', protocol: 'openai_chat', base_url: 'https://dashscope.aliyuncs.com/compatible-mode/v1', model: 'qwen3.8-flash', enabled: true, timeout_ms: 120000, max_tokens: 16000, system_prompt: '测试基础提示词', has_api_key: true }
const config = { profiles: [profile], system_default_id: 'qwen', default_id: 'qwen', review_default_id: 'qwen', revision: 1 }
const server = await createServer({ server: { host: '127.0.0.1', port: 0 }, appType: 'custom', logLevel: 'error' })
server.middlewares.use((req, res, next) => {
  if (req.url !== '/__model_test_controls') return next()
  res.setHeader('Content-Type', 'text/html; charset=utf-8')
  res.end(`<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;padding:24px;background:#f5f7fc;font-family:'Microsoft YaHei',sans-serif}*{box-sizing:border-box}</style></head><body><div id="app"></div><script type="module">import {createApp} from '/node_modules/.vite/deps/vue.js';import View from '/src/views/SpeechModelsView.vue';import '/src/style.css';createApp(View).mount('#app')</script></body></html>`)
})
await server.listen()
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const errors = [], calls = []
let hold = false, release
try {
  const page = await browser.newPage({ viewport: { width: 1680, height: 1050 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/api/v1/system/speech-models', route => {
    calls.push({ path: 'config', method: route.request().method() })
    return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ config, key_storage_ready: true }) })
  })
  await page.route('**/api/v1/system/speech-models/test-options', route => {
    const p = route.request().postDataJSON()
    return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ thinking: p.model === 'unknown-model' ? 'unavailable' : 'toggle', thinking_hint: p.model === 'unknown-model' ? '当前接口暂不支持切换思考模式' : '只用于本次文字测试', temperature_supported: true, temperature_max: p.protocol === 'anthropic' ? 1 : 2, temperature_disabled_when_thinking: p.protocol === 'anthropic' }) })
  })
  await page.route('**/api/v1/system/speech-models/test', async route => {
    const data = route.request().postDataJSON()
    calls.push({ path: 'test', method: 'POST', data })
    if (hold) await new Promise(resolve => { release = resolve })
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ text: Array.from({ length: 12 }, (_, i) => `第${i + 1}行：这是模型测试回答。`).join('\n'), model: data.profile.model, latency_ms: 12, input_tokens: 23, output_tokens: 54, total_tokens: 77 }) })
  })
  await page.goto(server.resolvedUrls.local[0] + '__model_test_controls')
  const input = page.getByRole('textbox', { name: '测试输入', exact: true })
  const answer = page.getByRole('textbox', { name: '模型输出', exact: true })
  const send = page.getByRole('button', { name: '发送', exact: true })
  const enter = page.getByRole('checkbox', { name: '回车发送', exact: true })
  const thinking = page.getByRole('switch', { name: '思考模式', exact: true })
  await input.waitFor()
  await thinking.waitFor()
  await page.waitForFunction(() => !document.querySelector('input[role=switch]').disabled)
  assert.equal(await input.getAttribute('rows'), '3')
  assert.equal(await answer.getAttribute('rows'), '5')
  assert.equal(await answer.getAttribute('readonly'), '')
  assert.ok((await answer.boundingBox()).y < (await input.boundingBox()).y)
  const heights = await page.evaluate(() => [...document.querySelectorAll('.test-output-text,.test-input-text')].map(el => ({ height: el.clientHeight, rows: el.rows, line: parseFloat(getComputedStyle(el).lineHeight), padding: parseFloat(getComputedStyle(el).paddingTop) + parseFloat(getComputedStyle(el).paddingBottom), resize: getComputedStyle(el).resize })))
  for (const box of heights) { assert.ok(Math.abs(box.height - (box.rows * box.line + box.padding)) <= 3); assert.equal(box.resize, 'none') }
  await input.fill('第一条测试问题')
  await input.press('Enter')
  assert.equal(calls.filter(c => c.path === 'test').length, 0)
  assert.ok((await input.inputValue()).includes('\n'))
  await page.getByRole('slider', { name: '模型温度' }).fill('0.25')
  await enter.check()
  await input.fill('请回答保存方法')
  await input.press('Shift+Enter')
  assert.equal(calls.filter(c => c.path === 'test').length, 0)
  await input.evaluate(el => el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', isComposing: true, bubbles: true, cancelable: true })))
  await input.evaluate(el => el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', keyCode: 229, bubbles: true, cancelable: true })))
  assert.equal(calls.filter(c => c.path === 'test').length, 0)
  await input.fill('请回答保存方法')
  await input.press('Enter')
  await page.waitForFunction(() => document.querySelector('.test-output-text').value.includes('第12行'))
  assert.equal(calls.filter(c => c.path === 'test').length, 1)
  assert.equal(calls.at(-1).data.question, '请回答保存方法')
  assert.equal(calls.at(-1).data.temperature, 0.25)
  assert.equal(calls.at(-1).data.enable_thinking, false)
  const outputHeight = await answer.evaluate(el => ({ height: el.clientHeight, scroll: el.scrollHeight }))
  assert.equal(outputHeight.height, heights[0].height)
  assert.ok(outputHeight.scroll > outputHeight.height)
  await thinking.check()
  await send.click()
  await page.waitForFunction(() => document.querySelector('.test-output-text').value.includes('第12行'))
  assert.equal(calls.at(-1).data.enable_thinking, true)
  await page.locator('.model-test').screenshot({ path: resolve(output, 'desktop.png') })

  hold = true
  const before = calls.filter(c => c.path === 'test').length
  await send.click()
  await page.waitForFunction(() => document.querySelector('.test-input-text').disabled)
  await input.evaluate(el => { el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })); el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', repeat: true, bubbles: true })) })
  assert.equal(calls.filter(c => c.path === 'test').length, before + 1, 'busy or held Enter sent duplicate paid requests')
  hold = false; release()
  await send.waitFor()
  await page.waitForFunction(() => !document.querySelector('.test-input-text').disabled)
  await input.fill('   ')
  assert.equal(await send.isDisabled(), true)
  await input.press('Enter')
  assert.equal(calls.filter(c => c.path === 'test').length, before + 1)

  await page.locator('.fields select').first().selectOption('anthropic')
  await page.waitForFunction(() => document.querySelector('input[type=range]').max === '1')
  assert.equal(await page.getByRole('slider', { name: '模型温度' }).isDisabled(), true)
  await input.fill('本次测试请回答')
  await send.click()
  await page.waitForFunction(() => document.querySelector('.test-output-text').value.includes('第12行'))
  assert.equal(calls.at(-1).data.temperature, undefined)
  await page.getByRole('button', { name: '测试连通性', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.test-input-text').disabled)
  assert.equal(calls.at(-1).data.mode, 'connectivity')
  assert.equal(calls.at(-1).data.temperature, undefined)
  assert.equal(calls.at(-1).data.enable_thinking, undefined)

  await page.locator('#speech-model-id').fill('unknown-model')
  await page.waitForFunction(() => document.querySelector('input[role=switch]').disabled && document.querySelector('.test-thinking small').textContent.includes('暂不支持'))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.model-test').scrollIntoViewIfNeeded()
  const mobile = await page.locator('.model-test').boundingBox()
  assert.ok(mobile.x >= 0 && mobile.x + mobile.width <= 391)
  await page.locator('.model-test').screenshot({ path: resolve(output, 'mobile.png') })
  assert.equal(calls.filter(c => c.method === 'PUT').length, 0, 'test controls changed saved model settings')
  assert.deepEqual(errors, [])
  const result = { passed: true, checks: ['output above input', 'fixed five-line output and three-line input', 'Enter opt-in and Shift+Enter newline', 'IME confirmation does not submit', 'temperature and thinking included in text test', 'long output scrolls without expanding', 'busy and repeat Enter cannot duplicate requests', 'empty question cannot send', 'thinking-dependent temperature omitted', 'connectivity test keeps short defaults', 'unsupported thinking visibly disabled', 'mobile fits', 'no settings save'], errors }
  await writeFile(resolve(output, 'result.json'), JSON.stringify(result, null, 2))
  console.log(JSON.stringify(result))
} finally { await browser.close(); await server.close() }
