import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const view = readFileSync(new URL('../src/views/InventoryLifecycleView.vue', import.meta.url), 'utf8')
const detail = view.slice(view.indexOf('<div v-if="inventoryDetailOpen'), view.indexOf('    <section v-else class="settings-card inventory-summary-panel">'))
const headers = [...detail.matchAll(/<th>([^<]+)<\/th>/g)].map(match => match[1])
assert.deepEqual(headers, ['设备名称','SN 码','MAC 地址','采购批次','当前仓库','状态','品质','当前归属','操作'])
const row = detail.match(/<tr v-for="item in detailDevices"[^>]*>([\s\S]*?)<\/tr>/)?.[1]
assert.ok(row)
const cells = [...row.matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/g)].map(match => match[1])
assert.equal(cells.length, 9)
assert.ok(cells[0].includes('selectedInventoryProduct.name'))
assert.ok(cells[1].includes('item.sn'))
assert.ok(cells[2].includes('item.hardware_mac'))
assert.ok(cells[5].includes('item.lifecycle_status') && !cells[5].includes('quality_status'))
assert.ok(cells[6].includes('item.quality_status') && !cells[6].includes('lifecycle_status'))
assert.ok(cells[2].includes('未登记'))
assert.ok(!detail.includes('PRODUCT INVENTORY'))
assert.match(view, /\.stock-detail-metrics > div \{ display: inline-flex; align-items: baseline/)
assert.match(view, /\.stock-detail-body \{ flex: 1 1 auto; min-height: 0; overflow: auto/)
assert.match(view, /\.stock-detail-toolbar \.stock-detail-status-filter \{ flex: 0 0 144px; width: 144px/)
assert.match(view, /\.stock-detail-toolbar \.stock-detail-page-size \{ flex: 0 0 116px; width: 116px/)
assert.match(detail, /v-model:page="detailPage"[^>]+@update:page="loadStockDetails"/)
assert.match(detail, /@click="openLedger\(item\)"/)
assert.match(detail, /@click="allowDeviceActivation\(item\)"/)
assert.ok(detail.indexOf('@click="allowDeviceActivation(item)"') < detail.indexOf('@click="openLedger(item)"'))
assert.ok(detail.includes('已激活'))
assert.ok(!view.includes("modal === 'hardware'"))
assert.ok(!view.includes('设备硬件登记与激活'))
console.log('Inventory detail: 9 separate columns, compact inline metrics, bounded filters, scrolling and pagination passed')
