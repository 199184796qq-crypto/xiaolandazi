import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
import { startFixture } from './model-picker-fixture.mjs'
const require = createRequire(new URL('../../collector-worker/package.json', import.meta.url))
const { chromium } = require('playwright-core')
const executablePath = [process.env.CHROME_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p => p && existsSync(p))
assert.ok(executablePath, 'Set CHROME_PATH to a Chromium executable')
const server = await startFixture()
const browser = await chromium.launch({ executablePath, headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const failures = []
  page.on('pageerror', error => { failures.push(error.message); console.error('Fixture error:', error.message) })
  page.on('console', msg => { if (msg.type() === 'error') console.error('Fixture console:', msg.text()) })
  page.on('response', r => { if (r.status() >= 400) console.error('Fixture HTTP:', r.status(), r.url()) })
  await page.goto('http://127.0.0.1:18598/__model-picker.html')
  const input = page.locator('#speech-model-id')
  await input.waitFor()
  const open = () => page.getByRole('button', { name: '刷新模型列表', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择模型' })
  const radios = dialog.getByRole('radio')
  await open()
  await radios.first().waitFor()
  assert.equal(await radios.count(), 10)
  assert.equal(await input.inputValue(), 'model-01')
  await dialog.getByRole('button', { name: '下一页' }).click()
  assert.equal(await radios.count(), 10)
  await dialog.getByRole('radio', { name: '选择 Special 模型（model-12）', exact: true }).check()
  assert.equal(await dialog.locator('input[type=radio]:checked').count(), 1)
  assert.equal(await input.inputValue(), 'model-01', 'checking must not commit')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  assert.equal(await input.inputValue(), 'model-01', 'cancel must preserve original')
  await open()
  await radios.first().waitFor()
  await dialog.getByRole('searchbox').fill('SPECIAL')
  assert.equal(await radios.count(), 1)
  await radios.first().check()
  await dialog.getByRole('button', { name: '选中', exact: true }).click()
  assert.equal(await input.inputValue(), 'model-12')
  assert.equal(await dialog.count(), 0)
  assert.equal(await page.evaluate(() => document.body.style.overflow), '')
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), '刷新模型列表')
  await open()
  await radios.first().waitFor()
  await dialog.getByRole('button', { name: '下一页' }).click()
  await dialog.getByRole('button', { name: '下一页' }).click()
  assert.equal(await radios.count(), 3)
  await dialog.getByRole('searchbox').fill('model-02')
  assert.equal(await radios.count(), 1, 'search resets page')
  await radios.first().check()
  await page.keyboard.press('Escape')
  assert.equal(await input.inputValue(), 'model-12', 'Escape must cancel')
  await page.evaluate(() => { window.fixture.delay = 250 })
  await open()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.waitForTimeout(350)
  assert.equal(await dialog.count(), 0, 'late response must not reopen panel')
  assert.equal(await input.inputValue(), 'model-12')
  await page.evaluate(() => { window.fixture.delay = 0; window.fixture.fail = true })
  await open()
  await dialog.getByRole('alert').waitFor()
  assert.equal(await dialog.getByRole('button', { name: '选中', exact: true }).isEnabled(), false)
  await page.evaluate(() => { window.fixture.fail = false; window.fixture.empty = true })
  await dialog.getByRole('button', { name: '刷新列表', exact: true }).click()
  await dialog.getByText('服务商未返回可选模型，可关闭面板后手动填写。', { exact: true }).waitFor()
  assert.equal(await radios.count(), 0)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await input.fill('manually-entered-model')
  assert.equal(await input.inputValue(), 'manually-entered-model')
  const calls = await page.evaluate(() => window.fixture.calls)
  assert.ok(calls.every(c => c.method === 'GET' || c.url.endsWith('/models')), 'no saves or generation during selection')
  assert.deepEqual(failures, [])
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => { window.fixture.empty = false })
  await open()
  await radios.first().waitFor()
  assert.ok(await dialog.evaluate(el => el.getBoundingClientRect().width <= 390))
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no mobile horizontal overflow')
  await page.screenshot({ path: '../artifacts/model-picker-mobile.png', fullPage: false })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await radios.first().check()
  await page.screenshot({ path: '../artifacts/model-picker-desktop.png', fullPage: false })
  console.log('Model picker passed: single choice, confirm/cancel/Escape, delayed response, search, 3 pages, errors, empty list, manual input, mobile fit; no writes or generation.')
} finally { await browser.close(); await server.close() }
