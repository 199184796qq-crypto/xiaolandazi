import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
import { startFixture } from './ops-rooms-fixture.mjs'
const require = createRequire(new URL('../../collector-worker/package.json', import.meta.url))
const {chromium} = require('playwright-core')
const executablePath = [process.env.CHROME_PATH,'C:/Program Files/Google/Chrome/Application/chrome.exe'].find(p=>p&&existsSync(p))
const server = await startFixture()
const browser = await chromium.launch({executablePath,headless:true})
try {
  const page=await browser.newPage({viewport:{width:1680,height:1000}}),errors=[]
  let stage='initial'
  page.on('pageerror',e=>{errors.push(e.message);console.log('pageerror stage:',stage)})
  await page.goto('http://127.0.0.1:18599/__ops-rooms.html')
  const table=page.locator('.ops-room-table'),oil=table.locator('tbody tr').filter({hasText:'菜籽油'}),date=table.locator('tbody tr').filter({hasText:'灰枣直播间'})
  await oil.waitFor()
  assert.equal(await table.locator('tbody tr').count(),2)
  assert.ok((await oil.textContent()).includes('小蓝客户'))
  assert.ok(!(await page.textContent('body')).includes('未知终端'))
  assert.equal((await page.evaluate(()=>window.fixture.calls)).filter(c=>c.url.endsWith('/customer-contact')).length,0,'no prefetch of phones')
  await oil.getByRole('button',{name:'查看小蓝客户的电话号码'}).click()
  await oil.getByText('13800000000',{exact:true}).waitFor()
  assert.ok(!(await page.evaluate(()=>JSON.stringify({...localStorage}))).includes('13800000000'),'phone must not be cached')
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.ops-phone-panel').count(),0)
  await page.evaluate(()=>{window.fixture.phoneDelay=200})
  await oil.getByRole('button',{name:'查看小蓝客户的电话号码'}).click()
  await oil.getByRole('button',{name:'查看小蓝客户的电话号码'}).click()
  await page.waitForTimeout(250)
  assert.equal(await page.locator('.ops-phone-panel').count(),0,'late response cannot reopen')
  await page.evaluate(()=>{window.fixture.phoneDelay=0;window.fixture.phoneEmpty=true})
  await date.getByRole('button',{name:'查看张三的电话号码'}).click()
  await date.getByText('该客户未填写电话号码',{exact:true}).waitFor()
  await page.getByRole('heading',{name:'直播间管理',exact:true}).click()
  assert.equal(await page.locator('.ops-phone-panel').count(),0,'outside click closes')
  await page.evaluate(()=>{window.fixture.phoneFail=true})
  await oil.getByRole('button',{name:'查看小蓝客户的电话号码'}).click()
  await oil.getByText('读取电话失败',{exact:true}).waitFor()
  await page.keyboard.press('Escape')
  await oil.locator('summary').click()
  assert.equal(await oil.getByRole('button',{name:'直播策略',exact:true}).count(),1)
  assert.equal(await oil.getByRole('button',{name:'重新连接',exact:true}).isEnabled(),false)
  assert.equal(await oil.getByRole('button',{name:'停止直播',exact:true}).isEnabled(),true)
  await page.screenshot({path:'../artifacts/ops-rooms-desktop.png',fullPage:true})
  await page.keyboard.press('Escape')
  assert.equal(await oil.locator('details').getAttribute('open'),null)
  await date.locator('summary').click()
  assert.equal(await date.getByRole('button',{name:'直播策略',exact:true}).count(),0,'no grant must hide strategy')
  await date.getByRole('button',{name:'删除直播间',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.fixture.feedbackState.confirmOpen),true)
  assert.ok((await page.evaluate(()=>window.fixture.feedbackState.confirmOptions.message)).includes('不能恢复'))
  await page.evaluate(()=>window.fixture.resolveConfirm(false))
  assert.equal((await page.evaluate(()=>window.fixture.calls)).filter(c=>c.method==='DELETE').length,0,'cancelling must not delete')
  stage='search'
  await page.getByRole('searchbox').fill('小蓝客户')
  assert.equal(await table.locator('tbody tr').count(),1,'search by customer name')
  await page.getByRole('searchbox').fill('')
  stage='revoke'
  await page.evaluate(()=>window.fixture.revoke())
  await page.waitForTimeout(100)
  assert.equal(await table.getByRole('button',{name:'直播策略',exact:true}).count(),0,'revocation removes entry')
  stage='entry'
  await oil.getByRole('button',{name:'进入直播间',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.fixture.router.currentRoute.value.path),'/rooms/15')
  stage='customer'
  await page.evaluate(()=>window.fixture.setCustomer())
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.ops-room-table').count(),0,'customer layout stays cards')
  assert.equal(await page.locator('.ops-phone-button').count(),0)
  assert.deepEqual(errors,[])
  console.log('Ops rooms passed: real names, on-demand phone/empty/error/race/no cache, menus, grant/revoke, delete confirmation cancel, customer search, entry route and unchanged customer cards.')
} finally {await browser.close();await server.close()}
