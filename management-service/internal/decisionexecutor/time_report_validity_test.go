package decisionexecutor

import (
	"testing"
	"time"
)

func TestTimeReportTemporalGranularity(t *testing.T) {
	for _, tc := range []struct {
		text, at, until string
		valid           bool
	}{
		{"下午了，大家歇一歇。", "2026-10-31 14:20:00", "2026-10-31 18:00:00", true},
		{"上午好！", "2026-10-31 10:20:00", "2026-10-31 12:00:00", true},
		{"都晚上了，谢谢陪伴。", "2026-10-31 23:59:50", "2026-11-01 00:00:00", true},
		{"夜里了，大家注意休息。", "2026-10-31 23:30:00", "2026-11-01 06:00:00", true},
		{"晚上深夜了，大家注意休息。", "2026-10-31 23:30:00", "2026-11-01 00:00:00", true},
		{"下午了，大家节奏慢一点。", "2026-10-31 14:30:00", "2026-10-31 18:00:00", true},
		{"都三点了。", "2026-10-31 15:30:00", "2026-10-31 16:00:00", true},
		{"现在下午三点半了。", "2026-10-31 15:30:10", "2026-10-31 15:31:00", true},
		{"十点一刻了。", "2026-10-31 10:15:10", "2026-10-31 10:16:00", true},
		{"现在15:40了。", "2026-10-31 15:40:55", "2026-10-31 15:41:00", true},
		{"再过十分钟要吃饭了。", "2026-10-31 11:22:30", "2026-10-31 11:23:00", true},
		{"感谢大家陪着聊。", "2026-10-31 14:20:00", "2026-10-31 18:00:00", true},
		{"下午好。", "2026-10-31 18:00:00", "", false},
		{"现在15:40了。", "2026-10-31 15:41:00", "", false},
		{"现在四点了。", "2026-10-31 15:40:00", "", false},
		{"昨天晚上了。", "2026-10-31 20:40:00", "", false},
	} {
		t.Run(tc.text+tc.at, func(t *testing.T) {
			at, _ := time.ParseInLocation("2006-01-02 15:04:05", tc.at, beijingZone)
			until, valid := timeReportValidity(tc.text, at)
			if valid != tc.valid {
				t.Fatalf("valid=%v until=%s", valid, until)
			}
			if valid && until.In(beijingZone).Format("2006-01-02 15:04:05") != tc.until {
				t.Fatal(until.In(beijingZone))
			}
		})
	}
}
